#!/usr/bin/env python3
"""Extract Merak Plan demo transcript fields and score them with the eval harness."""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from typing import Any

from merak_plan_eval_report import SCENARIOS
from merak_plan_eval_report import evaluate_submission
from merak_plan_eval_report import finding


BORDER_RE = re.compile(r"^=+$")
KEY_RE = re.compile(r"^([A-Za-z][A-Za-z -]+):\s*(.*)$")
KEY_TO_FIELD = {
    "Scenario ID": "scenario_id",
    "Question topics": "question_topics",
    "Tool guidance": "tool_guidance",
    "Scope in": "scope_in",
    "Scope out": "scope_out",
    "Success metric": "success_metric",
    "Counter-metric": "counter_metric",
    "Evidence artifacts": "evidence_artifacts",
    "Discoverable unknowns": "discoverable_unknowns",
    "User decisions": "user_decisions",
    "Confidence gaps": "confidence_gaps",
    "Planning Summary Review": "planning_summary",
    "Residual risks": "residual_risks",
}
LIST_FIELDS = {
    "question_topics",
    "tool_guidance",
    "evidence_artifacts",
    "scope_in",
    "scope_out",
    "residual_risks",
    "discoverable_unknowns",
    "user_decisions",
    "confidence_gaps",
}
EXPECTED_DEMO_SCENARIOS = {"ambiguous-goal", "backend-work", "demo-generation"}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--transcript",
        type=Path,
        default=Path("artifacts/merak-plan-demo/merak-plan-demo.txt"),
        help="Terminal transcript generated by scripts/merak_plan_demo.py.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("artifacts/merak-plan-demo"),
        help="Directory for extracted submissions and reports.",
    )
    args = parser.parse_args()

    submissions = extract_submissions(args.transcript.read_text(encoding="utf-8"))
    report = evaluate_demo_submissions(submissions)

    args.output_dir.mkdir(parents=True, exist_ok=True)
    submissions_path = args.output_dir / "merak-plan-demo-extracted-submissions.json"
    json_report_path = args.output_dir / "merak-plan-demo-eval-report.json"
    markdown_report_path = args.output_dir / "merak-plan-demo-eval-report.md"

    submissions_path.write_text(
        json.dumps(submissions, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    json_report_path.write_text(
        json.dumps(report, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    markdown_report_path.write_text(markdown_report(report), encoding="utf-8")

    print(f"wrote {submissions_path}")
    print(f"wrote {json_report_path}")
    print(f"wrote {markdown_report_path}")
    print(
        "merak_plan_demo_eval_summary "
        f"passed={report['summary']['passed']} "
        f"failed={report['summary']['failed']} "
        f"total={report['summary']['total']}"
    )
    return 0 if report["summary"]["failed"] == 0 else 1


def extract_submissions(transcript: str) -> list[dict[str, Any]]:
    submissions: list[dict[str, Any]] = []
    for frame in frames(transcript):
        title = first_non_empty_line(frame)
        if not title.endswith("- executable plan"):
            continue

        fields = parse_key_values(frame)
        submission = normalize_submission(fields)
        if submission:
            submissions.append(submission)
    return submissions


def frames(transcript: str) -> list[list[str]]:
    frames: list[list[str]] = []
    current: list[str] = []
    inside_frame = False
    for line in transcript.splitlines():
        if BORDER_RE.match(line):
            if inside_frame and current:
                frames.append(current)
            current = []
            inside_frame = not inside_frame
            continue
        if inside_frame:
            current.append(line.rstrip())
    return frames


def first_non_empty_line(lines: list[str]) -> str:
    for line in lines:
        stripped = line.strip()
        if stripped:
            return stripped
    return ""


def parse_key_values(lines: list[str]) -> dict[str, str]:
    fields: dict[str, str] = {}
    current_key: str | None = None
    for raw_line in lines:
        line = raw_line.strip()
        if not line:
            continue

        match = KEY_RE.match(line)
        if match and match.group(1) in KEY_TO_FIELD:
            current_key = KEY_TO_FIELD[match.group(1)]
            fields[current_key] = match.group(2).strip()
            continue

        if current_key is not None:
            fields[current_key] = f"{fields[current_key]} {line}".strip()
    return fields


def normalize_submission(fields: dict[str, str]) -> dict[str, Any]:
    if "scenario_id" not in fields:
        return {}
    submission: dict[str, Any] = {"scenario_id": fields["scenario_id"]}
    for field, value in fields.items():
        if field == "scenario_id":
            continue
        if field in LIST_FIELDS:
            submission[field] = split_list(value)
        else:
            submission[field] = value.strip()
    return submission


def split_list(value: str) -> list[str]:
    return [item.strip() for item in value.split(",") if item.strip()]


def evaluate_demo_submissions(submissions: list[dict[str, Any]]) -> dict[str, Any]:
    scenarios_by_id = {scenario.id: scenario for scenario in SCENARIOS}
    submissions_by_id = {submission.get("scenario_id"): submission for submission in submissions}
    results = []

    for scenario_id in sorted(EXPECTED_DEMO_SCENARIOS):
        scenario = scenarios_by_id[scenario_id]
        submission = submissions_by_id.get(scenario_id)
        if submission is None:
            findings = [finding("missing_demo_submission", f"missing demo submission for {scenario_id}")]
        else:
            findings = evaluate_submission(scenario, submission)
        results.append(
            {
                "scenario_id": scenario_id,
                "category": scenario.category,
                "prompt": scenario.prompt,
                "passed": not findings,
                "findings": findings,
            }
        )

    for scenario_id in sorted(set(submissions_by_id) - EXPECTED_DEMO_SCENARIOS):
        results.append(
            {
                "scenario_id": scenario_id,
                "category": "Unexpected",
                "prompt": "",
                "passed": False,
                "findings": [
                    finding("unexpected_demo_submission", f"unexpected demo scenario {scenario_id}")
                ],
            }
        )

    passed = sum(1 for result in results if result["passed"])
    failed = len(results) - passed
    return {
        "summary": {
            "passed": passed,
            "failed": failed,
            "total": len(results),
            "expected_demo_scenarios": sorted(EXPECTED_DEMO_SCENARIOS),
        },
        "results": results,
    }


def markdown_report(report: dict[str, Any]) -> str:
    summary = report["summary"]
    lines = [
        "# Merak Plan Demo Eval Report",
        "",
        f"- Passed: {summary['passed']}/{summary['total']}",
        f"- Failed: {summary['failed']}",
        f"- Expected demo scenarios: {', '.join(summary['expected_demo_scenarios'])}",
        "",
        "| Scenario | Category | Result | Findings |",
        "| --- | --- | --- | --- |",
    ]
    for result in report["results"]:
        status = "PASS" if result["passed"] else "FAIL"
        findings = "; ".join(finding["kind"] for finding in result["findings"]) or "-"
        lines.append(
            f"| {result['scenario_id']} | {result['category']} | {status} | {findings} |"
        )
    lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    raise SystemExit(main())
